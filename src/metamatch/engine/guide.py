"""
Coach Guide written by the engine. Every line comes from data the app already computes: the Threat Board
(damage calcs against the format's most used Pokemon), final Speed against ladder spreads, each member's
real moves, and the type chart. Nothing is generated by a language model, so the guide can't name a move
a member doesn't run or a mechanic that doesn't exist, and it works with Ollama off.
"""
from dataclasses import dataclass, field, replace

from metamatch import config
from metamatch.engine import speed_board
from metamatch.engine import threat_board as tb
from metamatch.engine import synergy
from metamatch.engine.constraints import SETUP_MOVES
from metamatch.engine.dex import dex_for_format
from metamatch.type_chart import get_multiplier

TYPES = ["Normal", "Fire", "Water", "Electric", "Grass", "Ice", "Fighting", "Poison", "Ground",
         "Flying", "Psychic", "Bug", "Rock", "Ghost", "Dragon", "Dark", "Steel", "Fairy"]
HAZARDS = ("Stealth Rock", "Spikes", "Toxic Spikes", "Sticky Web")
REMOVAL = ("Rapid Spin", "Defog", "Mortal Spin", "Court Change", "Tidy Up")
PIVOTS = ("U-turn", "Volt Switch", "Flip Turn", "Parting Shot", "Teleport", "Shed Tail", "Chilly Reception")
N_THREATS = 12
# Setup moves for the guide: the constraint parser's list plus the ones it never needs to read from a question
SETUP = set(SETUP_MOVES) | {"Growth", "Coil", "Work Up", "Shift Gear", "Curse", "Tail Glow", "Geomancy",
                            "Clangorous Soul", "No Retreat", "Fillet Away", "Rock Polish"}
N_SPEED = 25
STAT_LABELS = {"hp": "HP", "atk": "Atk", "def": "Def", "spa": "SpA", "spd": "SpD", "spe": "Spe"}


def _and(names):
    names = list(names)
    if not names:
        return ""
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def _pct(x):
    return f"{x * 100:.0f}%"


@dataclass
class Member:
    name: str
    beats: list            # top threats it beats one on one
    loses: list            # top threats that beat it
    speed: int
    outspeeds: float       # share of the top ladder sets it outspeeds, Choice Scarf mixed in
    setup: list
    priority: list
    hazards: list
    removal: list
    pivots: list
    attacks: list          # damaging moves as (name, type)
    types: list
    weak: list             # types that hit it for 2x or more
    tera: str = ""


@dataclass
class Guide:
    format_id: str
    n_threats: int
    win: dict | None = None
    leads: list = field(default_factory=list)
    tera: list = field(default_factory=list)     # SV: every member's Tera, best first
    mega: list = field(default_factory=list)     # Champions: each Mega holder
    combos: list = field(default_factory=list)
    watch: list = field(default_factory=list)
    engines: list = field(default_factory=list)  # synergy.Engine: the cores the team runs, complete first

    def named_members(self):
        """Every team member the guide names, for checks."""
        names = [self.win["name"]] if self.win else []
        names += [x["name"] for x in self.leads + self.tera + self.mega] + [n for c in self.combos for n in c["pair"]]
        names += [n for w in self.watch for n in w["answers"]]
        names += [s["name"] for e in self.engines for s in e.setters] + [u.name for e in self.engines for u in e.users]
        return names


def board_rows(team, format_id, n=N_THREATS):
    """Threat Board rows as plain dicts, the same shape the Threat Board tab caches."""
    rows = tb.threat_board(team, n=n, format_id=format_id)
    return [{"name": r.name, "usage": r.usage, "answers": r.answers, "losses": r.losses} for r in rows]


def member_facts(team, format_id, rows):
    """Per member facts (beats, loses, Speed, setup, priority, roles...) shared by the guide and the team banner."""
    dex = dex_for_format(format_id)
    speeds = speed_board.member_speeds(team, format_id)
    meta = speed_board.meta_speeds(format_id, n=N_SPEED, exclude=[p["Pokemon"] for p in team.values()])
    out = []
    for p in team.values():
        name = p["Pokemon"]
        moves = [m["name"] for m in p.get("Moves", [])]
        data = {m: (dex.move(m) or {}) if dex else {} for m in moves}
        attacks = [(m, data[m].get("type") or mv.get("type")) for m, mv in zip(moves, p.get("Moves", []))
                   if (data[m].get("category") or mv.get("category")) != "Status"]
        speed = speeds.get(name) or p.get("Speed", 0)
        out.append(Member(
            name=name,
            beats=[r["name"] for r in rows if name in r["answers"]],
            loses=[r["name"] for r in rows if name in r["losses"]],
            speed=speed,
            outspeeds=sum(speed_board.outspeed_share(speed, m) for m in meta) / len(meta) if meta else 0.0,
            setup=[m for m in moves if m in SETUP],
            priority=[m for m, _ in attacks if data[m].get("priority", 0) > 0],
            hazards=[m for m in moves if m in HAZARDS],
            removal=[m for m in moves if m in REMOVAL],
            pivots=[m for m in moves if m in PIVOTS],
            attacks=attacks,
            types=list(p.get("Type") or []),
            weak=[t for t in TYPES if (p.get("Damage From") or {}).get(t.lower(), 1.0) >= 2],
            tera=p.get("Tera Type") or "",
        ))
    return out


def _engine_boosts(engines):
    """{member: (sentence, 2HKOs with the core up, share of the top 25 outspeeded with it up)} for each member a
    complete core powers up. The win condition ranks those members by what they do with their core in play."""
    out = {}
    for e in engines:
        if not e.complete:
            continue
        for u in e.users:
            if u.major and u.name not in out and (u.speed or u.damage):
                share = u.speed[3] if u.speed else 0.0
                lines = [synergy.headline(e, u)]
                if u.speed:   # the headline is about Speed, so its knockouts come next
                    lines += [pt for pt in u.points if " 2HKOs " in pt][-1:]
                out[u.name] = (lines, u.peak, share)
    return out


def _win(members, n, boosts=None):
    """The member most likely to win the game for you: wins the most top matchups, sets up, moves first, and is
    what the team's core (sun, rain, Trick Room...) is built to power up."""
    boosts = boosts or {}
    fighters = [m for m in members if m.attacks]
    if not fighters:
        return None
    def score(m):
        _, peak, share = boosts.get(m.name, ([], 0, 0.0))
        return (max(len(m.beats), peak) + 1.5 * bool(m.setup) + 0.5 * bool(m.priority) + 2 * max(m.outspeeds, share)
                + 1.0 * (m.name in boosts))
    m = max(fighters, key=score)
    points = [f"Beats {len(m.beats)} of the {n} most used Pokémon one on one"]
    if m.name in boosts:
        points = boosts[m.name][0] + points
    if m.setup:
        points.append(f"Runs {_and(m.setup)} to set up")
    if m.priority:
        points.append(f"Has {_and(m.priority)} for priority")
    # A core user's Speed line already says what it outspeeds with the core up
    if m.outspeeds >= 0.5 and not (m.name in boosts and boosts[m.name][2]):
        points.append(f"Outspeeds {_pct(m.outspeeds)} of the top {N_SPEED} Pokémon's ladder sets")
    text = f"{m.name} is your best route to a win. " + " ".join(p + "." for p in points)
    keep = (f"Keep it healthy until these are worn down: {_and(m.loses[:3])}." if m.loses
            else "None of the top threats beats it one on one.")
    return {"name": m.name, "text": text, "points": points, "keep": keep, "threats": m.loses[:3]}


def _leads(members, n, win_name, setters=None):
    """Two leads: weather and terrain setters (they set it on entry) and hazard setters first, then pivots, then
    whoever wins the most matchups and moves first. setters: {member: 'Sets sun on entry with Drought'}."""
    setters = setters or {}
    pool = [m for m in members if m.name != win_name] or members
    score = lambda m: 3 * bool(m.hazards) + 2.5 * (m.name in setters) + 1.5 * bool(m.pivots) + len(m.beats) / max(n, 1) + m.outspeeds
    out = []
    for m in sorted(pool, key=score, reverse=True)[:2]:
        jobs = [setters[m.name]] if m.name in setters else []
        if m.hazards:
            jobs.append(f"Sets {_and(m.hazards)}")
        if m.pivots:
            jobs.append(f"Pivots out with {_and(m.pivots)}")
        if m.removal and not jobs:
            jobs.append(f"Clears hazards with {_and(m.removal)}")
        points = jobs + [f"Beats {len(m.beats)} of the {n} most used Pokémon one on one"]
        if m.outspeeds >= 0.5:
            points.append(f"Outspeeds {_pct(m.outspeeds)} of the top {N_SPEED} Pokémon's ladder sets")
        out.append({"name": m.name, "points": points})
    return out


def _weak_to(types):
    return [t for t in TYPES if _mult(t, types) >= 2]


def _mult(attack, types):
    x = 1.0
    for t in types:
        x *= get_multiplier(attack, t)
    return x


WEATHER_BALL = {"sun": "Fire", "rain": "Water", "sand": "Rock", "snow": "Ice"}


def _tera(members, engines=()):
    """Every member's Tera: weaknesses before and after, and what it does for its attacks. Best first.
    Weather Ball counts as the type the team's weather makes it (a Fire move on a sun team)."""
    ball = next((WEATHER_BALL[e.key] for e in engines if e.key in WEATHER_BALL and e.setters), None)
    out = []
    for m in members:
        if not m.tera:
            continue
        if ball:
            m = replace(m, attacks=[(mv, ball if mv == "Weather Ball" else t) for mv, t in m.attacks])
        attack_types = {t for _, t in m.attacks}
        if m.tera == "Stellar":
            after, note = list(m.weak), "Stellar keeps its own typing and boosts each attacking type once"
        else:
            after = _weak_to([m.tera])
            boosted = [mv for mv, t in m.attacks if t == m.tera]
            verb = ("goes", "gains") if len(boosted) == 1 else ("go", "gain")
            if boosted and m.tera in m.types:
                note = f"{_and(boosted)} {verb[0]} from 1.5x to 2x STAB"
            elif boosted:
                note = f"{_and(boosted)} {verb[1]} STAB"
            else:
                note = "Purely defensive: none of its attacks are " + m.tera
        removed = [t for t in m.weak if t not in after]
        added = [t for t in after if t not in m.weak]
        score = len(removed) - len(added) + (0.5 if m.tera in attack_types else 0)
        out.append({"name": m.name, "tera": m.tera, "before": list(m.weak), "after": after, "removed": removed,
                    "added": added, "note": note, "score": score})
    out.sort(key=lambda x: x["score"], reverse=True)
    for i, x in enumerate(out):
        x["best"] = i == 0 and x["score"] > 0
    return out


def _mega(team, format_id):
    """Champions Megas: the stat and typing changes Mega Evolution brings, straight from the dex."""
    dex = dex_for_format(format_id)
    out = []
    for p in team.values():
        forme = p.get("Forme") or ""
        if "-Mega" not in forme or not dex:
            continue
        base, mega = dex.species(p["Pokemon"]) or {}, dex.species(forme) or {}
        b, s = base.get("baseStats", {}), mega.get("baseStats", {})
        gains = [f"{'+' if s[k] > b[k] else ''}{s[k] - b[k]} {STAT_LABELS[k]}" for k in STAT_LABELS if k in s and k in b and s[k] != b[k]]
        points = [f"Holds {p.get('Item')}"] if p.get("Item") else []
        if gains:
            points.append("Base stats " + ", ".join(gains))
        if mega.get("types") and mega["types"] != base.get("types"):
            points.append(f"Becomes {' / '.join(mega['types'])} type")
        ability = p.get("Mega Ability") or (mega.get("abilities") or [None])[0]
        if ability:
            points.append(f"Gets {ability}")
        out.append({"name": p["Pokemon"], "forme": forme, "points": points})
    return out


def _combos(members, n=3):
    """Pairs that cover each other: one beats the threats that beat the other, or takes the types it fears."""
    scored = []
    for i, a in enumerate(members):
        for b in members[i + 1:]:
            b_covers = [t for t in a.loses if t in b.beats]
            a_covers = [t for t in b.loses if t in a.beats]
            b_takes = [t for t in a.weak if _mult(t, b.types) < 1]
            a_takes = [t for t in b.weak if _mult(t, a.types) < 1]
            score = len(b_covers) + len(a_covers) + 0.5 * (len(b_takes) + len(a_takes))
            if score:
                scored.append((score, a, b, b_covers, a_covers, b_takes, a_takes))
    scored.sort(key=lambda x: x[0], reverse=True)
    out, used = [], {}
    for score, a, b, b_covers, a_covers, b_takes, a_takes in scored:
        # Spread the picks: no member in more than two combos
        if used.get(a.name, 0) >= 2 or used.get(b.name, 0) >= 2:
            continue
        points = []
        if b_covers:
            points.append(f"{b.name} beats {_and(b_covers[:3])}, which {'beats' if len(b_covers[:3]) == 1 else 'beat'} {a.name}")
        if a_covers:
            points.append(f"{a.name} beats {_and(a_covers[:3])}, which {'beats' if len(a_covers[:3]) == 1 else 'beat'} {b.name}")
        if b_takes:
            points.append(f"{b.name} resists {_and(b_takes)} for {a.name}")
        if a_takes:
            points.append(f"{a.name} resists {_and(a_takes)} for {b.name}")
        out.append({"pair": [a.name, b.name], "points": points})
        used[a.name] = used.get(a.name, 0) + 1
        used[b.name] = used.get(b.name, 0) + 1
        if len(out) == n:
            break
    return out


def _watch(rows, n=3):
    """The most used threats the team answers thinly: one answer or none."""
    thin = [r for r in rows if len(r["answers"]) <= 1]
    out = []
    for r in thin[:n]:
        if r["answers"]:
            text = f"Only {r['answers'][0]} beats it one on one"
        else:
            text = "Nobody on your team beats it one on one"
        out.append({"name": r["name"], "usage": r["usage"], "answers": list(r["answers"]), "text": text})
    return out


def team_guide(team, format_id=None, rows=None):
    """The whole guide for a team. rows: Threat Board rows as dicts (board_rows), computed when not given."""
    format_id = format_id or config.team_format(team)
    rows = board_rows(team, format_id) if rows is None else rows
    members = member_facts(team, format_id, rows)
    n = len(rows)
    guide = Guide(format_id, n)
    guide.engines = synergy.team_engines(team, format_id)
    guide.win = _win(members, n, _engine_boosts(guide.engines))
    entry = {}
    for e in guide.engines:
        for st in e.setters:
            if st["ability"] and st["name"] not in entry:
                entry[st["name"]] = f"Sets {synergy._label(e)} on entry with {st['how'][0].replace(' on entry', '')}"
    guide.leads = _leads(members, n, guide.win["name"] if guide.win else None, entry)
    if config.format_game(format_id) == "champions":
        guide.mega = _mega(team, format_id)
    else:
        guide.tera = _tera(members, guide.engines)
    guide.combos = _combos(members)
    guide.watch = _watch(rows)
    return guide

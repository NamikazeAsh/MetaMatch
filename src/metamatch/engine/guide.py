"""
Coach Guide written by the engine. Every line comes from data the app already computes: the Threat Board
(damage calcs against the format's most used Pokemon), final Speed against ladder spreads, each member's
real moves, and the type chart. Nothing is generated by a language model, so the guide can't name a move
a member doesn't run or a mechanic that doesn't exist, and it works with Ollama off.
"""
from dataclasses import dataclass, field, replace

from metamatch import config, meta_trends
from metamatch.engine import abilities, speed_board
from metamatch.engine import threat_board as tb
from metamatch.engine import synergy
from metamatch.engine.moves import HAZARDS, PIVOTS, REMOVAL, SETUP, is_priority
from metamatch.engine.dex import dex_for_format
from metamatch.type_chart import get_multiplier

TYPES = ["Normal", "Fire", "Water", "Electric", "Grass", "Ice", "Fighting", "Poison", "Ground",
         "Flying", "Psychic", "Bug", "Rock", "Ghost", "Dragon", "Dark", "Steel", "Fairy"]
N_THREATS = 12
N_SPEED = 25
# Lead score weight on how often ladder players lead with a member (bench/guide/leads.py --tune picks it)
LEAD_RATE_WEIGHT = 10.0
LEAD_PRIOR = meta_trends.LEAD_PRIOR
STAT_LABELS = {"hp": "HP", "atk": "Atk", "def": "Def", "spa": "SpA", "spd": "SpD", "spe": "Spe"}


def _and(names):
    names = list(names)
    if not names:
        return ""
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def _pct(x):
    return f"{x * 100:.0f}%"


@dataclass
class Member:
    name: str
    beats: list            # top threats it beats one on one
    loses: list            # top threats that beat it
    speed: int
    outspeeds: float       # share of the top ladder sets it outspeeds, Choice Scarf mixed in
    setup: list
    priority: list
    hazards: list
    removal: list
    pivots: list
    attacks: list          # damaging moves as (name, type)
    types: list
    weak: list             # types that hit it for 2x or more
    tera: str = ""


@dataclass
class Guide:
    format_id: str
    n_threats: int
    win: dict | None = None
    leads: list = field(default_factory=list)
    tera: list = field(default_factory=list)     # SV OU and UU: every member's Tera, best first
    mega: list = field(default_factory=list)     # Champions and National Dex: each Mega holder
    combos: list = field(default_factory=list)
    watch: list = field(default_factory=list)
    engines: list = field(default_factory=list)  # synergy.Engine: the cores the team runs, complete first
    hazards: dict | None = None                  # hazards.hazard_plan: what entry hazards cost the team
    six: list = field(default_factory=list)      # each member: its jobs, what it switches into, what it must leave

    def named_members(self):
        """Every team member the guide names, for checks."""
        names = [self.win["name"]] if self.win else []
        names += [a["member"] for w in self.watch for a in (w.get("switch"), w.get("revenge")) if a]
        names += [x["name"] for x in self.leads + self.tera + self.mega] + [n for c in self.combos for n in c["pair"]]
        names += [n for w in self.watch for n in w["answers"]]
        names += [s["name"] for e in self.engines for s in e.setters] + [u.name for e in self.engines for u in e.users]
        return names


def board_rows(team, format_id, n=N_THREATS):
    """Threat Board rows as plain dicts, the same shape the Threat Board tab caches (with each cell's numbers)."""
    rows = tb.threat_board(team, n=n, format_id=format_id)
    return [{"name": r.name, "usage": r.usage, "answers": r.answers, "losses": r.losses,
             "cells": {m: {"verdict": c.verdict, "n": tb.cell_numbers(c.exchange)} for m, c in r.cells.items()}}
            for r in rows]


def member_facts(team, format_id, rows):
    """Per member facts (beats, loses, Speed, setup, priority, roles...) shared by the guide and the team banner."""
    dex = dex_for_format(format_id)
    speeds = speed_board.member_speeds(team, format_id)
    meta = speed_board.meta_speeds(format_id, n=N_SPEED, exclude=[p["Pokemon"] for p in team.values()])
    out = []
    for p in team.values():
        name = p["Pokemon"]
        moves = [m["name"] for m in p.get("Moves", [])]
        data = {m: (dex.move(m) or {}) if dex else {} for m in moves}
        attacks = [(m, data[m].get("type") or mv.get("type")) for m, mv in zip(moves, p.get("Moves", []))
                   if (data[m].get("category") or mv.get("category")) != "Status"]
        speed = speeds.get(name) or p.get("Speed", 0)
        out.append(Member(
            name=name,
            beats=[r["name"] for r in rows if name in r["answers"]],
            loses=[r["name"] for r in rows if name in r["losses"]],
            speed=speed,
            outspeeds=sum(speed_board.outspeed_share(speed, m) for m in meta) / len(meta) if meta else 0.0,
            setup=[m for m in moves if m in SETUP],
            priority=[m for m, _ in attacks if is_priority(m, [p.get("Ability"), p.get("Mega Ability")])],
            hazards=[m for m in moves if m in HAZARDS],
            removal=[m for m in moves if m in REMOVAL],
            pivots=[m for m in moves if m in PIVOTS],
            attacks=attacks,
            types=list(p.get("Type") or []),
            weak=[t for t in TYPES if (p.get("Damage From") or {}).get(t.lower(), 1.0) >= 2],
            tera=p.get("Tera Type") or "",
        ))
    return out


def _engine_boosts(engines):
    """{member: (sentence, 2HKOs with the core up, share of the top 25 outspeeded with it up)} for each member a
    complete core powers up. The win condition ranks those members by what they do with their core in play."""
    out = {}
    for e in engines:
        if not e.complete:
            continue
        for u in e.users:
            if u.major and u.name not in out and (u.speed or u.damage):
                share = u.speed[3] if u.speed else 0.0
                lines = [synergy.headline(e, u)]
                if u.speed:   # the headline is about Speed, so its knockouts come next
                    lines += [pt for pt in u.points if " 2HKOs " in pt][-1:]
                out[u.name] = (lines, u.peak, share)
    return out


def _win(members, n, boosts=None):
    """The member most likely to win the game for you: wins the most top matchups, sets up, moves first, and is
    what the team's core (sun, rain, Trick Room...) is built to power up."""
    boosts = boosts or {}
    fighters = [m for m in members if m.attacks]
    if not fighters:
        return None
    def score(m):
        _, peak, share = boosts.get(m.name, ([], 0, 0.0))
        return (max(len(m.beats), peak) + 1.5 * bool(m.setup) + 0.5 * bool(m.priority) + 2 * max(m.outspeeds, share)
                + 1.0 * (m.name in boosts))
    m = max(fighters, key=score)
    points = [f"Beats {len(m.beats)} of the {n} most used Pokémon one on one"]
    if m.name in boosts:
        points = boosts[m.name][0] + points
    if m.setup:
        points.append(f"Runs {_and(m.setup)} to set up")
    if m.priority:
        points.append(f"Has {_and(m.priority)} for priority")
    # A core user's Speed line already says what it outspeeds with the core up
    if m.outspeeds >= 0.5 and not (m.name in boosts and boosts[m.name][2]):
        points.append(f"Outspeeds {_pct(m.outspeeds)} of the top {N_SPEED} Pokémon's ladder sets")
    text = f"{m.name} is your best route to a win. " + " ".join(p + "." for p in points)
    keep = (f"Keep it healthy until these are worn down: {_and(m.loses[:3])}." if m.loses
            else "None of the top threats beats it one on one.")
    return {"name": m.name, "text": text, "points": points, "keep": keep, "threats": m.loses[:3]}


def _leads(members, n, win_name, setters=None, rates=None):
    """Two leads: weather and terrain setters (they set it on entry) and hazard setters first, then pivots, then
    whoever wins the most matchups and moves first, nudged by how often ladder players lead with it.
    setters: {member: 'Sets sun on entry with Drought'}; rates: meta_trends.lead_rates, {member: (rate, listed)}."""
    setters, rates = setters or {}, rates or {}
    pool = [m for m in members if m.name != win_name] or members
    def score(m):
        rate = rates.get(m.name, (None, False))[0]
        return (3 * bool(m.hazards) + 2.5 * (m.name in setters) + 1.5 * bool(m.pivots) + len(m.beats) / max(n, 1)
                + m.outspeeds + LEAD_RATE_WEIGHT * ((LEAD_PRIOR if rate is None else rate) - LEAD_PRIOR))
    out = []
    for m in sorted(pool, key=score, reverse=True)[:2]:
        jobs = [setters[m.name]] if m.name in setters else []
        if m.hazards:
            jobs.append(f"Sets {_and(m.hazards)}")
        if m.pivots:
            jobs.append(f"Pivots out with {_and(m.pivots)}")
        if m.removal and not jobs:
            jobs.append(f"Clears hazards with {_and(m.removal)}")
        points = jobs + [f"Beats {len(m.beats)} of the {n} most used Pokémon one on one"]
        rate, listed = rates.get(m.name, (None, False))
        if listed:
            points.append(f"Leads {_pct(rate)} of the ladder games it's in")
        if m.outspeeds >= 0.5:
            points.append(f"Outspeeds {_pct(m.outspeeds)} of the top {N_SPEED} Pokémon's ladder sets")
        out.append({"name": m.name, "points": points})
    return out


def _weak_to(types):
    return [t for t in TYPES if _mult(t, types) >= 2]


def _mult(attack, types):
    x = 1.0
    for t in types:
        x *= get_multiplier(attack, t)
    return x


WEATHER_BALL = {"sun": "Fire", "rain": "Water", "sand": "Rock", "snow": "Ice"}


def _tera(members, engines=()):
    """Every member's Tera: weaknesses before and after, and what it does for its attacks. Best first.
    Weather Ball counts as the type the team's weather makes it (a Fire move on a sun team)."""
    ball = next((WEATHER_BALL[e.key] for e in engines if e.key in WEATHER_BALL and e.setters), None)
    out = []
    for m in members:
        if not m.tera:
            continue
        if ball:
            m = replace(m, attacks=[(mv, ball if mv == "Weather Ball" else t) for mv, t in m.attacks])
        attack_types = {t for _, t in m.attacks}
        if m.tera == "Stellar":
            after, note = list(m.weak), "Stellar keeps its own typing and boosts each attacking type once"
        else:
            after = _weak_to([m.tera])
            boosted = [mv for mv, t in m.attacks if t == m.tera]
            verb = ("goes", "gains") if len(boosted) == 1 else ("go", "gain")
            if boosted and m.tera in m.types:
                note = f"{_and(boosted)} {verb[0]} from 1.5x to 2x STAB"
            elif boosted:
                note = f"{_and(boosted)} {verb[1]} STAB"
            else:
                note = "Purely defensive: none of its attacks are " + m.tera
        removed = [t for t in m.weak if t not in after]
        added = [t for t in after if t not in m.weak]
        score = len(removed) - len(added) + (0.5 if m.tera in attack_types else 0)
        out.append({"name": m.name, "tera": m.tera, "before": list(m.weak), "after": after, "removed": removed,
                    "added": added, "note": note, "score": score})
    out.sort(key=lambda x: x["score"], reverse=True)
    for i, x in enumerate(out):
        x["best"] = i == 0 and x["score"] > 0
    return out


def _add_recommended_tera(tera_cards, team, format_id):
    """Adds what Smogon's closest set recommends and what the ladder runs to each Tera card, and whether the team's
    own pick is one of them (engine/tera.py)."""
    from metamatch.engine import tera as tera_data
    by_name = {p["Pokemon"]: p for p in (team or {}).values()}
    for x in tera_cards:
        p = by_name.get(x["name"]) or {}
        moves = [m["name"] for m in p.get("Moves", []) if m.get("name")]
        x["smogon"] = tera_data.closest(x["name"], format_id, moves, p.get("Item"))
        x["ladder"] = tera_data.ladder(x["name"], format_id)
        x["standing"] = tera_data.standing(x["name"], format_id, x["tera"])
        # The team's Tera recommended on a different Smogon set than the closest one: name that set too, so a pick
        # counted as Smogon's never looks unrecommended on the card
        x["smogon_other"] = None
        if x["smogon"] and x["tera"] not in x["smogon"][1]:
            x["smogon_other"] = next((name for name, types in tera_data.smogon(x["name"], format_id)
                                      if x["tera"] in types), None)


def _mega(team, format_id):
    """Megas (Champions, National Dex): the stat and typing changes Mega Evolution brings, straight from the dex."""
    dex = dex_for_format(format_id)
    out = []
    for p in team.values():
        forme = p.get("Forme") or ""
        if "-Mega" not in forme or not dex:
            continue
        base, mega = dex.species(p["Pokemon"]) or {}, dex.species(forme) or {}
        b, s = base.get("baseStats", {}), mega.get("baseStats", {})
        gains = [f"{'+' if s[k] > b[k] else ''}{s[k] - b[k]} {STAT_LABELS[k]}" for k in STAT_LABELS if k in s and k in b and s[k] != b[k]]
        points = [f"Holds {p.get('Item')}"] if p.get("Item") else []
        if gains:
            points.append("Base stats " + ", ".join(gains))
        if mega.get("types") and mega["types"] != base.get("types"):
            points.append(f"Becomes {' / '.join(mega['types'])} type")
        ability = p.get("Mega Ability") or (mega.get("abilities") or [None])[0]
        if ability:
            points.append(f"Gets {ability}")
        # The raw before and after, for the card's stat bars, type icons and ability chips
        out.append({"name": p["Pokemon"], "forme": forme, "points": points, "item": p.get("Item"),
                    "base_stats": {k: b.get(k) for k in STAT_LABELS}, "mega_stats": {k: s.get(k) for k in STAT_LABELS},
                    "base_types": base.get("types") or [], "mega_types": mega.get("types") or [],
                    "base_ability": p.get("Ability"), "mega_ability": ability,
                    "smogon": _mega_smogon(p, forme, format_id)})
    return out


def _mega_smogon(p, forme, format_id):
    """(label, preview, [the rest, by paragraph]) of Smogon's write up of this Mega here, or None (rag/cards.py)."""
    try:
        from metamatch.rag.cards import mega_analysis
        return mega_analysis(p["Pokemon"], forme, [m["name"] for m in p.get("Moves", []) if m.get("name")], format_id)
    except Exception as e:   # the analysis is a bonus: never let it break the guide
        print(f"Mega analysis failed: {e}")
        return None


def _takes(types, defender_types):
    """'is immune to Ground and resists Grass, Bug and Fairy': an immunity is a free switch into that attack,
    so it is said apart from a resistance rather than folded into one."""
    immune = [t for t in types if _mult(t, defender_types) == 0]
    resist = [t for t in types if t not in immune]
    parts = ([f"is immune to {_and(immune)}"] if immune else []) + ([f"resists {_and(resist)}"] if resist else [])
    return " and ".join(parts)


def _combos(members, n=3):
    """Pairs that cover each other: one beats the threats that beat the other, or takes the types it fears."""
    scored = []
    for i, a in enumerate(members):
        for b in members[i + 1:]:
            b_covers = [t for t in a.loses if t in b.beats]
            a_covers = [t for t in b.loses if t in a.beats]
            b_takes = [t for t in a.weak if _mult(t, b.types) < 1]
            a_takes = [t for t in b.weak if _mult(t, a.types) < 1]
            score = len(b_covers) + len(a_covers) + 0.5 * (len(b_takes) + len(a_takes))
            if score:
                scored.append((score, a, b, b_covers, a_covers, b_takes, a_takes))
    scored.sort(key=lambda x: x[0], reverse=True)
    out, used = [], {}
    for score, a, b, b_covers, a_covers, b_takes, a_takes in scored:
        # Spread the picks: no member in more than two combos
        if used.get(a.name, 0) >= 2 or used.get(b.name, 0) >= 2:
            continue
        points = []
        if b_covers:
            points.append(f"{b.name} beats {_and(b_covers[:3])}, which {'beats' if len(b_covers[:3]) == 1 else 'beat'} {a.name}")
        if a_covers:
            points.append(f"{a.name} beats {_and(a_covers[:3])}, which {'beats' if len(a_covers[:3]) == 1 else 'beat'} {b.name}")
        if b_takes:
            points.append(f"{b.name} {_takes(b_takes, b.types)} for {a.name}")
        if a_takes:
            points.append(f"{a.name} {_takes(a_takes, a.types)} for {b.name}")
        out.append({"pair": [a.name, b.name], "points": points})
        used[a.name] = used.get(a.name, 0) + 1
        used[b.name] = used.get(b.name, 0) + 1
        if len(out) == n:
            break
    return out


def _watch(rows, n=3):
    """The most used threats the team answers thinly (one answer or none), each with who switches into it and who
    knocks it out, read from the board's numbers (one on one, full HP, the threat's most common set)."""
    thin = [r for r in rows if len(r["answers"]) <= 1]
    out = []
    for r in thin[:n]:
        if r["answers"]:
            text = f"Only {r['answers'][0]} beats it one on one"
        else:
            text = "Nobody on your team beats it one on one"
        numbers = {m: c["n"] for m, c in (r.get("cells") or {}).items() if c.get("n")}
        out.append({"name": r["name"], "usage": r["usage"], "answers": list(r["answers"]), "text": text,
                    "switch": _switch_in(numbers), "revenge": _revenge(numbers)})
    return out


# The jobs worth naming first when a member has several (team.detectRole's vocabulary); the banner uses it too
JOB_ORDER = ["Setup Sweeper", "Hazard Setter", "Hazard Remover", "Pivot", "Wall", "Tank", "Priority User", "Revenge Killer",
             "Spin Blocker", "Special Sweeper", "Physical Sweeper", "Fast Sweeper", "Bulky Attacker", "Speed Control"]
SIX_SHOWN = 3


def _six(team, rows):
    """Each member at a glance: up to two jobs, the top threats it can switch into (the one switch in rule, and it
    doesn't lose the one on one) and the ones it must get out against (they knock it out in one hit, or are faster,
    beat it and need only two hits; a long slow loss isn't a reason to leave). Most used first; one hit knockouts
    lead the second list."""
    out = []
    for p in team.values():
        name = p["Pokemon"]
        roles = p.get("Roles") or []
        safe, leave = [], []
        for r in rows:
            c = (r.get("cells") or {}).get(name) or {}
            n = c.get("n")
            if not n:
                continue
            if tb.safe_switch(n) and c.get("verdict") != "lose":
                tip = (f"takes at most {_pct_hit(n['taken_hi'])} from {n['taken_move']}" if n.get("taken_move")
                       else "its usual attacks do nothing")
                safe.append({"name": r["name"], "tip": tip})
            elif n.get("to_be_koed") == 1 or (c.get("verdict") == "lose" and n["outspeeds"] < 0.5
                                               and (n.get("to_be_koed") or 99) <= 2):
                one = n.get("to_be_koed") == 1
                tip = f"{n['taken_move']} does up to {_pct_hit(n['taken_hi'])}" + (", a one hit knockout" if one else "")
                leave.append({"name": r["name"], "tip": tip, "one": one})
        leave.sort(key=lambda x: not x["one"])   # stable: most used first within each group
        out.append({"name": name, "jobs": [j for j in JOB_ORDER if j in roles][:2] or roles[:2],
                    "safe": safe[:SIX_SHOWN], "out": leave[:SIX_SHOWN]})
    return out


def _pct_hit(x):
    return f"{x:.0f}%"


def _switch_in(numbers):
    """{member, text, safe} for the member that takes the least from the threat, or None without numbers."""
    if not numbers:
        return None
    m, n = min(numbers.items(), key=lambda mn: (mn[1]["taken_hi"], -(mn[1].get("to_be_koed") or 99)))
    if not tb.safe_switch(n):
        return {"member": m, "safe": False, "text": f"No safe switch in. {m} takes the least, up to {_pct_hit(n['taken_hi'])}"}
    if not n.get("taken_move"):
        return {"member": m, "safe": True, "text": f"Switch in {m}: its usual attacks do nothing to it"}
    if n["taken_hi"] >= 50:   # safe because it takes three or more hits, not because one hit is small
        return {"member": m, "safe": True,
                "text": f"Switch in {m}: {n['taken_move']} does up to {_pct_hit(n['taken_hi'])}, but it survives a second hit"}
    return {"member": m, "safe": True,
            "text": f"Switch in {m}: takes at most {_pct_hit(n['taken_hi'])} from {n['taken_move']}"}


def _revenge(numbers):
    """{member, text} for the member that knocks the threat out from full HP: faster and in one hit, else a priority
    move in one hit, else faster in two hits (wear it down first). None when nobody does."""
    fast_one = [(m, n) for m, n in numbers.items() if n.get("to_ko") == 1 and n["outspeeds"] >= 0.5]
    if fast_one:
        m, _ = max(fast_one, key=lambda mn: mn[1]["outspeeds"])
        return {"member": m, "text": f"{m} outspeeds it and knocks it out in one hit"}
    prio = [(m, n) for m, n in numbers.items() if n.get("to_ko") == 1 and n.get("prio_move")]
    if prio:
        m, n = prio[0]
        return {"member": m, "text": f"{m}'s {n['prio_move']} knocks it out in one hit"}
    fast_two = [(m, n) for m, n in numbers.items() if n.get("to_ko") == 2 and n["outspeeds"] >= 0.5]
    if fast_two:
        m, _ = max(fast_two, key=lambda mn: mn[1]["outspeeds"])
        return {"member": m, "text": f"Wear it down first: {m} is faster and needs two hits"}
    return None


def fix_target(team, rows, guide):
    """{hole, swap} for the one fix that helps most, or None: the biggest hole is the most used threat nothing beats
    (else one that only one member beats); the member to swap is the one doing least against the top threats (beats,
    plus half credit for safe switch ins), never the win condition, a setter of a core the team runs, the only hazard
    setter or remover, Magic Bounce on a team with no removal, the Mega holder, or the hole's one answer. The pick
    itself comes from the Team Completer (fix_pick)."""
    hole = next((r for r in rows if not r["answers"]), None) or next((r for r in rows if len(r["answers"]) == 1), None)
    if not hole:
        return None
    keep = {guide.win["name"]} if guide.win else set()
    keep |= {st["name"] for e in guide.engines if e.complete for st in e.setters}
    keep |= set(hole["answers"])
    h = guide.hazards or {}
    for side in ("setters", "removers"):
        if len(h.get(side) or []) == 1:
            keep.add(h[side][0]["name"])
    if not h.get("removers"):   # with no removal, Magic Bounce is the team's only hazard control
        keep |= set(h.get("bounce") or [])
    keep |= {p["Pokemon"] for p in team.values() if "-Mega" in (p.get("Forme") or "")}
    # What a member does against the top threats: the ones it beats, and half credit for the ones it switches into,
    # so a wall that wins few one on ones but takes hits all game isn't the first to go
    def value(name):
        beats = sum(name in r["answers"] for r in rows)
        takes = sum(tb.safe_switch(((r.get("cells") or {}).get(name) or {}).get("n")) for r in rows)
        return beats + 0.5 * takes, -sum(name in r["losses"] for r in rows)
    pool = [p["Pokemon"] for p in team.values() if p["Pokemon"] not in keep]
    if not pool:
        return None
    swap = min(pool, key=value)
    return {"hole": {"name": hole["name"], "usage": hole["usage"], "answers": list(hole["answers"])}, "swap": swap}


def fix_pick(picks, hole):
    """The Team Completer pick for the fix: the best one that beats the hole, else the best overall; None when no
    pick beats anything. picks: the completer's candidates as dicts, best first."""
    useful = [c for c in picks if c.get("covers")]
    return next((c for c in useful if hole in c["covers"]), None) or (useful[0] if useful else None)


def _add_abilities(guide, team, format_id):
    """One ability line on the win condition card (what it does for the sweep, measured where the calc can) and on
    a lead card when the ability acts the moment it comes in (Intimidate, Magic Bounce, Prankster...)."""
    cards = ([guide.win] if guide.win else []) + guide.leads
    try:
        lines = abilities.ability_lines(team, format_id, names={c["name"] for c in cards})
    except Exception:
        return
    for card in cards:
        line = lines.get(card["name"])
        if not line or (card is not guide.win and not line.lead):
            continue
        at = next((i for i, pt in enumerate(card["points"]) if pt.startswith("Beats ")), len(card["points"]))
        card["points"].insert(at, line.text)
    if guide.win:
        guide.win["text"] = f"{guide.win['name']} is your best route to a win. " + " ".join(p + "." for p in guide.win["points"])


def team_guide(team, format_id=None, rows=None):
    """The whole guide for a team. rows: Threat Board rows as dicts (board_rows), computed when not given."""
    format_id = format_id or config.team_format(team)
    rows = board_rows(team, format_id) if rows is None else rows
    members = member_facts(team, format_id, rows)
    n = len(rows)
    guide = Guide(format_id, n)
    guide.engines = synergy.team_engines(team, format_id)
    guide.win = _win(members, n, _engine_boosts(guide.engines))
    entry = {}
    for e in guide.engines:
        for st in e.setters:
            if st["ability"] and st["name"] not in entry:
                entry[st["name"]] = f"Sets {synergy._label(e)} on entry with {st['how'][0].replace(' on entry', '')}"
    try:
        rates = meta_trends.lead_rates(format_id, [m.name for m in members])
    except Exception:
        rates = {}
    guide.leads = _leads(members, n, guide.win["name"] if guide.win else None, entry, rates)
    _add_abilities(guide, team, format_id)
    # Each format gets the gimmick it allows: Mega cards in Champions and National Dex, the Tera plan in SV OU and UU
    if config.has_megas(format_id):
        guide.mega = _mega(team, format_id)
    if config.has_tera(format_id):
        guide.tera = _tera(members, guide.engines)
        _add_recommended_tera(guide.tera, team, format_id)
    guide.combos = _combos(members)
    guide.watch = _watch(rows)
    guide.six = _six(team, rows)
    try:
        from metamatch.engine.hazards import hazard_plan   # imports this module, so loaded here
        guide.hazards = hazard_plan(team, format_id)
    except Exception as e:   # a bonus section: never let it break the guide
        print(f"Hazard plan failed: {e}")
    return guide
